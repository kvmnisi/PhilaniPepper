// Vercel build step: writes js/env.js from environment variables.
//   API_BASE_URL  backend the hosted UI should call, e.g. https://my-tunnel.example
// Run locally with: API_BASE_URL=http://localhost:8000 node build-env.js
var fs = require("fs");
var path = require("path");

var env = {
  apiBaseUrl: process.env.API_BASE_URL || null,
  runtime: process.env.APP_RUNTIME || null
};
var body = "/* Generated by build-env.js. Do not edit on the build server. */\n" +
  "window.APP_ENV = " + JSON.stringify(env) + ";\n";
fs.writeFileSync(path.join(__dirname, "js", "env.js"), body);
console.log("Wrote js/env.js", env);
