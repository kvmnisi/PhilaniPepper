#!/usr/bin/env python3
"""Copy frontend/ into pepper_app/html/ for the Choregraphe package.

    python scripts/sync_pepper_html.py           # write the Pepper copy
    python scripts/sync_pepper_html.py --check   # exit 1 if the copy is stale

Differences from the web build:
  * js/env.js sets runtime "pepper", so the page talks to NAOqi instead of
    recording in the browser (Pepper's tablet has no usable microphone).
  * CSS custom properties are replaced by their values, because the NAOqi 2.5
    tablet WebView may predate var() support.
  * Only font files tracked for distribution (Grotesk-Medium.ttf) are copied;
    other font binaries stay local (see frontend/assets/fonts/README.md).
"""

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "frontend"
DST = ROOT / "pepper_app" / "html"
INCLUDE = ["index.html", "css", "js", "assets", "vendor"]
SKIP_SUFFIXES = {".ttf", ".otf", ".woff", ".woff2"}
ALLOWED_FONTS = {"Grotesk-Medium.ttf"}
PEPPER_ENV = (
    "/* Generated by scripts/sync_pepper_html.py for the Pepper tablet. */\n"
    'window.APP_ENV = { apiBaseUrl: null, runtime: "pepper" };\n'
)


def inline_css_variables(css):
    root = re.search(r":root\s*\{([^}]*)\}", css)
    if not root:
        return css
    values = dict(re.findall(r"(--[\w-]+)\s*:\s*([^;]+);", root.group(1)))

    def resolve(match):
        name, fallback = match.group(1), match.group(2)
        if name in values:
            return values[name].strip()
        return fallback.strip() if fallback else match.group(0)

    pattern = re.compile(r"var\(\s*(--[\w-]+)\s*(?:,\s*([^()]*))?\)")
    for _ in range(3):  # resolve variables that reference variables
        css = pattern.sub(resolve, css)
    return css


def build():
    """Return {relative path: bytes} for the Pepper copy."""
    files = {}
    for entry in INCLUDE:
        path = SRC / entry
        paths = [path] if path.is_file() else sorted(p for p in path.rglob("*") if p.is_file())
        for item in paths:
            if item.suffix.lower() in SKIP_SUFFIXES and item.name not in ALLOWED_FONTS:
                continue
            rel = item.relative_to(SRC).as_posix()
            data = item.read_bytes()
            if rel == "js/env.js":
                data = PEPPER_ENV.encode("utf-8")
            elif rel.endswith(".css"):
                data = inline_css_variables(data.decode("utf-8")).encode("utf-8")
            files[rel] = data
    return files


def existing():
    if not DST.exists():
        return {}
    return {
        p.relative_to(DST).as_posix(): p.read_bytes()
        for p in DST.rglob("*")
        if p.is_file() and (p.suffix.lower() not in SKIP_SUFFIXES or p.name in ALLOWED_FONTS)
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    wanted, current = build(), existing()
    if args.check:
        stale = sorted(set(wanted) ^ set(current) | {k for k in wanted if current.get(k) != wanted[k]})
        if stale:
            print("pepper_app/html is out of date: " + ", ".join(stale))
            print("Run: python scripts/sync_pepper_html.py")
            return 1
        print("pepper_app/html is up to date.")
        return 0

    for rel in set(current) - set(wanted):
        (DST / rel).unlink()
    for rel, data in wanted.items():
        target = DST / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    print("Wrote %d files to %s" % (len(wanted), DST.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
